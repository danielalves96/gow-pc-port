#!/usr/bin/env python3
"""Builds gow_menu_patch.h: a binary delta that turns the retail FLP_HUD movie into the movie with the Port Options and Cheats pages.

usage: make_delta.py <original FLP_HUD.bin> <patched output of flp_patch_cheats.py (movie + T8, with .t9 and .split)> <out header>

The delta is a list of operations over the original movie: copy(offset, length) takes bytes from the retail movie and
literal(bytes) inserts new bytes (the new texts, actions and table records). The header carries the CRC32 and size of the
retail movie it applies to and of the result, so the runtime applies it only to the exact retail movie and verifies the
output. The T9 table (read-only color multipliers, kept outside the movie to save memory) is copied from the original.
"""
import sys, zlib

MIN_MATCH = 12
# The game itself writes heap bookkeeping into a table of the loaded movie (records "ff ff NN 00 96 00 xx 0b 00 00" near 0x1FF4C),
# so the bytes of that window differ between the file and memory. Checksums ignore the window and the copies that overlap it
# keep whatever the game has there, as it does for the original menu.
VOL_LO, VOL_HI = 0x1FF30, 0x20000

def crc_masked(data, ranges):
    d = bytearray(data)
    for lo, hi in ranges: d[lo:hi] = bytes(hi - lo)
    return zlib.crc32(bytes(d))

def copy_masks(blob):
    """output ranges produced by copy operations over the volatile window"""
    ranges = []; out = 0; p = 0
    def rd():
        nonlocal p
        v = 0; s = 0
        while True:
            c = blob[p]; p += 1; v |= (c & 0x7F) << s; s += 7
            if not c & 0x80: return v
    while True:
        t = blob[p]; p += 1
        if t == 2: return ranges
        if t == 0:
            n = rd(); p += n; out += n
        else:
            o = rd(); n = rd()
            lo, hi = max(o, VOL_LO), min(o + n, VOL_HI)
            if lo < hi: ranges.append((out + lo - o, out + hi - o))
            out += n

def varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F; n >>= 7
        if n: out.append(b | 0x80)
        else: out.append(b); return bytes(out)

def build(a, b):
    idx = {}
    for i in range(len(a) - MIN_MATCH + 1):
        idx.setdefault(a[i:i + MIN_MATCH], []).append(i)
    ops = []; i = 0; n = len(b); lit = None
    while i < n:
        best = (0, 0)
        if i + MIN_MATCH <= n:
            for j in idx.get(b[i:i + MIN_MATCH], [])[:64]:
                l = MIN_MATCH
                while i + l < n and j + l < len(a) and a[j + l] == b[i + l]: l += 1
                if l > best[0]: best = (l, j)
        if best[0] >= MIN_MATCH:
            if lit is not None: ops.append(("L", b[lit:i])); lit = None
            ops.append(("C", best[1], best[0])); i += best[0]
        else:
            if lit is None: lit = i
            i += 1
    if lit is not None: ops.append(("L", b[lit:n]))
    return ops

def encode(ops):
    out = bytearray()
    for op in ops:
        if op[0] == "L": out += b"\x00" + varint(len(op[1])) + op[1]
        else: out += b"\x01" + varint(op[1]) + varint(op[2])
    out += b"\x02"
    return bytes(out)

def apply(a, blob):
    out = bytearray(); p = 0
    def rd():
        nonlocal p
        v = 0; s = 0
        while True:
            c = blob[p]; p += 1; v |= (c & 0x7F) << s; s += 7
            if not c & 0x80: return v
    while True:
        t = blob[p]; p += 1
        if t == 2: return bytes(out)
        if t == 0:
            n = rd(); out += blob[p:p + n]; p += n
        else:
            o = rd(); n = rd(); out += a[o:o + n]

def main_shell(a, b):
    """The title menu movie (FLP_Shell): the patched movie is complete (tables included) and is parsed in a block of its own, so the
    header has no T8/T9 split and no volatile window."""
    blob = encode(build(a, b))
    assert apply(a, blob) == b
    crc_a = zlib.crc32(a); crc_b = zlib.crc32(b)
    lines = []
    for k in range(0, len(blob), 16):
        lines.append("    " + ", ".join("0x%02X" % x for x in blob[k:k + 16]) + ",")
    text = f"""// GOW-Port: binary delta of the retail FLP_Shell movie (the title menu) that adds the Port Options item and its pages (GOW_NATIVE_CHEATS_MENU=1).
// Generated by RustPortPS2/native/tools/menu/make_patch.py (needs the user's own PART1.PAK); do not edit by hand.
// It holds no copy of the game's data: the copy operations only refer to offsets inside the retail movie, and the literals are
// the records written for the new item and pages. The runtime applies it to the movie the game loaded, and only when that movie
// has the size and checksum listed here. The patched movie does not fit the original buffer, so it is parsed in a block of its own.
#pragma once
#include <cstdint>

namespace gow_menu_patch_shell
{{
    constexpr uint32_t kOriginalSize = {len(a)}u;
    constexpr uint32_t kOriginalCrc32 = 0x{crc_a:08X}u;
    constexpr uint32_t kPatchedSize = {len(b)}u;
    constexpr uint32_t kPatchedCrc32 = 0x{crc_b:08X}u;

    // 0: literal(varint length, bytes)   1: copy(varint offset, varint length)   2: end
    static const uint8_t kOps[] = {{
{chr(10).join(lines)}
    }};
}}
"""
    open(sys.argv[3], "w", encoding="utf-8", newline="\n").write(text)
    print("delta: %d ops bytes, original crc %08x, patched crc %08x, patched size %d" % (len(blob), crc_a, crc_b, len(b)))

def main():
    a = open(sys.argv[1], "rb").read(); b = open(sys.argv[2], "rb").read()
    if len(sys.argv) > 4 and sys.argv[4] == "shell":
        main_shell(a, b); return
    t9 = open(sys.argv[2] + ".t9", "rb").read()
    split = int(open(sys.argv[2] + ".split").read())      # the output is the movie (split bytes) followed by its T8 table
    t9_off = a.find(t9)
    assert t9_off >= 0 and a.find(t9, t9_off + 1) < 0, "the T9 table must appear exactly once in the original movie"
    blob = encode(build(a, b))
    assert apply(a, blob) == b
    masks = copy_masks(blob)
    crc_a = crc_masked(a, [(VOL_LO, VOL_HI)]); crc_b = crc_masked(b, masks)
    lines = []
    for k in range(0, len(blob), 16):
        lines.append("    " + ", ".join("0x%02X" % x for x in blob[k:k + 16]) + ",")
    text = f"""// GOW-Port: binary delta of the retail FLP_HUD movie that adds Port Options and its Cheats pages to the pause menu (GOW_NATIVE_CHEATS_MENU=1).
// Generated by RustPortPS2/native/tools/menu/make_patch.py (needs the user's own PART1.PAK); do not edit by hand.
// It holds no copy of the game's data: the copy operations only refer to offsets inside the retail movie, and the literals are
// the records written for those pages (new texts, actions, table entries and the fields they changed). The runtime applies
// it to the movie the game loaded, and only when that movie has the size and checksum listed here.
#pragma once
#include <cstdint>

namespace gow_menu_patch
{{
    constexpr uint32_t kOriginalSize = {len(a)}u;
    constexpr uint32_t kOriginalCrc32 = 0x{crc_a:08X}u;    // ignoring the volatile window
    constexpr uint32_t kPatchedSize = {len(b)}u;      // movie + T8 table
    constexpr uint32_t kMovieSize = {split}u;         // the movie part: it is written over the original buffer
    constexpr uint32_t kT8Size = {len(b) - split}u;      // the T8 table part: it lives in a block of its own
    constexpr uint32_t kPatchedCrc32 = 0x{crc_b:08X}u;     // ignoring the output of copies over the window
    constexpr uint32_t kVolatileBegin = 0x{VOL_LO:X}u, kVolatileEnd = 0x{VOL_HI:X}u;
    constexpr uint32_t kT9Offset = {t9_off}u; // read-only table of the original movie, moved out of the patched movie
    constexpr uint32_t kT9Size = {len(t9)}u;

    // 0: literal(varint length, bytes)   1: copy(varint offset, varint length)   2: end
    static const uint8_t kOps[] = {{
{chr(10).join(lines)}
    }};
}}
"""
    open(sys.argv[3], "w", encoding="utf-8", newline="\n").write(text)
    print("delta: %d ops bytes, original crc %08x, patched crc %08x, T9 at %d, %d masked ranges" % (len(blob), crc_a, crc_b, t9_off, len(masks)))

main()
